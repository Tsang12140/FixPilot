def _build_context(texts: List[str]) -> str:
    if not texts:
        return "（本次未检索到相关知识块）"
    blocks = "\n\n".join(f"[片段]\n{t}" for t in texts)
    return f"以下是知识库中检索到的相关内容，请据此回答：\n\n{blocks}"


def stream_chat(messages: List[Dict[str, str]]) -> Iterator[str]:
    """messages: 已完成的历史对话（role/content）。"""
    url = config.DEEPSEEK_BASE_URL.rstrip("/") + "/chat/completions"
    headers = {
        "Authorization": f"Bearer {config.DEEPSEEK_API_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": config.DEEPSEEK_MODEL,
        "messages": messages,
        "stream": True,
        "temperature": 0.8,
        "max_tokens": 1500,
    }
    with httpx.stream("POST", url, headers=headers, json=payload, timeout=120) as resp:
        resp.raise_for_status()
        for line in resp.iter_lines():
            if not line or not line.startswith("data:"):
                continue
            data = line[len("data:"):].strip()
            if data == "[DONE]":
                break
            try:
                chunk = json.loads(data)
                delta = chunk["choices"][0]["delta"].get("content", "")
                if delta:
                    yield delta
            except (json.JSONDecodeError, KeyError, IndexError):
                continue